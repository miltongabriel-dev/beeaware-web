-- One-off: backfill municipality geometry for the 18 states that had
-- NEVER had backfillGeometry() run for them at all (found while building
-- nearby_news_pins, 20260830120000 — that RPC needs a real polygon
-- centroid per city_ibge_code, and querying geo_areas directly showed
-- PR/SC/GO/PI/PB/MA/PE/CE/RN/TO/MS/SE/AM/RO/AC/AP/RR/DF each at 0/N
-- municipalities with geometry, vs. full coverage for RJ/MG/BA/AL/MT/ES/
-- PA/RS/SP from the two earlier backfill migrations). Without this, any
-- news article city-matched to one of these 18 states' municipalities
-- (which is most of them — this is roughly half the country, several
-- state capitals included, e.g. João Pessoa/PB had zero geometry) would
-- silently never produce a map pin. Same fire-and-forget net.http_post
-- pattern as 20260826170000/20260826180000.
select net.http_post(
  url := 'https://brjzkdtkmewbodpqjhkj.supabase.co/functions/v1/ingest-security-sources',
  headers := jsonb_build_object(
    'Authorization', 'Bearer ' || (select decrypted_secret from vault.decrypted_secrets where name = 'service_role_key'),
    'Content-Type', 'application/json'
  ),
  body := jsonb_build_object('action', 'backfill-geometry', 'stateCode', 'PR')
);
